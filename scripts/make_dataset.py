"""Fixed-seed, noisy synthetic flight logs from the Rumoca JAX export."""
from __future__ import annotations
import argparse
import csv
import time
from common import *


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "data")
    args = parser.parse_args()
    start = time.perf_counter()
    _, export = compile_model()
    rollout = jax_rollout(export)
    p = parameters(export, **TRUTH_DRAG)
    rng = np.random.default_rng(20261012)
    noise_std = np.array([0.025, 0.025, 0.001, 0.035, 0.035, 0.003])
    experiments = []
    rows = []
    for i, vx0 in enumerate([0.4, 3.0, 6.0, -4.5]):
        split = "train" if i < 3 else "validation"
        x0, u = maneuver(export, vx0=vx0, amplitude=0.23 if i < 3 else 0.32,
                         frequency=0.8 if i < 3 else 0.95)
        y = np.asarray(rollout(p, x0, u))
        noisy = y + rng.normal(size=y.shape)*noise_std
        # Known initial state is an explicit workshop assumption.
        noisy[0] = x0
        commands = np.vstack((u, u[-1]))  # terminal row has no outgoing interval
        for k in range(len(y)):
            rows.append([i, split, f"{k*DT:.8f}", *commands[k], *noisy[k]])
        experiments.append({"id": i, "split": split, "initial_state": x0.tolist(),
                            "vx_range": [float(y[:, 3].min()), float(y[:, 3].max())]})
    args.output.mkdir(parents=True, exist_ok=True)
    with (args.output / "noisy_flight.csv").open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["flight", "split", "time", "T", "tau", *STATE_NAMES])
        writer.writerows(rows)
    write_json(args.output / "truth.json", {
        "seed": 20261012, "dt": DT, "drag": TRUTH_DRAG,
        "noise_std": dict(zip(STATE_NAMES, noise_std.tolist())),
        "source_sha256": source_hash(), "rumoca_version": rm.version(),
        "experiments": experiments,
        "provenance": "Synthetic; generated by Rumoca to_jax RHS with fixed-step RK4. Not real flight data.",
        "initial_state_assumption": "Initial state known exactly; measurement noise added only after t=0."})
    print(f"Saved {len(rows)} noisy samples / 4 flights in {time.perf_counter()-start:.2f}s")


if __name__ == "__main__":
    main()
