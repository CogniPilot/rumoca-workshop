import {createRequire} from 'node:module';
import os from 'node:os';
const require=createRequire((process.env.WORKSHOP_UI_TOOLS || os.homedir()+'/scratch/rumoca-workshop/browser')+'/package.json');
const {chromium}=require('playwright-core');
import fs from 'node:fs';
import assert from 'node:assert/strict';
const [root]=process.argv.slice(2);
const source=fs.readFileSync(root+'/browser/Quadrotor_browser.mo','utf8');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox'],headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('dialog',dialog=>dialog.accept('rumoca-scenario.browserflight.toml'));
await page.goto('https://cognipilot.github.io/rumoca/',{waitUntil:'domcontentloaded',timeout:60000});
await page.getByText('Runtime: Ready',{exact:true}).waitFor({timeout:60000});
// Workspace initialization can replace the starter editor before Ready.
await page.waitForTimeout(1000);
const runs=[];
for(const k of [0,0.08]){
 if(k!==0) await page.getByRole('button',{name:'Main.mo',exact:true}).first().click();
 const code=k===0?source:source.replace('= 0.0 "EXERCISE','= 0.08 "EXERCISE');
 await page.evaluate(s=>window.editor.setValue(s),code);
 await page.getByText(/Compile: Balanced/).waitFor({timeout:30000});
 if(k===0) await page.locator('#editorCodegenBtn').click();
 else await page.getByRole('button',{name:'rumoca-scenario.browserflight.toml',exact:true}).first().click();
 await page.waitForTimeout(1000);
 const settings=page.frames().find(frame=>frame.url()==='about:srcdoc');
 assert.ok(settings,'Create Scenario must open the typed settings editor');
 await settings.getByLabel('Model name',{exact:true}).fill('BrowserFlight');
 await settings.getByLabel('Batch end time',{exact:true}).fill('8');
 await settings.locator('#saveBtn').click();
 const started=Date.now();
 await settings.locator('#runBtn').click();
 await page.getByText('Simulation completed: BrowserFlight',{exact:true}).waitFor({timeout:30000});
 await page.waitForTimeout(1200);
 const text=await page.locator('body').innerText();
 assert.ok(text.includes('BrowserFlight Results'));
 assert.ok(text.includes('501 points, 8 variables'));
 assert.ok(text.includes('States vs Time'));
 assert.deepEqual(errors,[]);
 runs.push({k_quad:k,elapsed_seconds:(Date.now()-started)/1000,summary:text.match(/501 points, 8 variables \([^)]*\)/)?.[0],model:'BrowserFlight',t_end:8});
 await page.screenshot({path:root+`/slides/assets/browser-drag-${k===0?'linear':'quadratic'}.png`,fullPage:true});
}
await page.getByRole('button',{name:'Main.mo',exact:true}).first().click();
await page.evaluate(()=>window.editor.setValue('model Broken\n Real x = ;\nend Broken;'));
await page.waitForFunction(()=>window.monaco.editor.getModelMarkers({owner:'rumoca'}).length>0,{timeout:10000});
const markers=await page.evaluate(()=>window.monaco.editor.getModelMarkers({owner:'rumoca'}).map(m=>({message:m.message,startLineNumber:m.startLineNumber})));
fs.writeFileSync(root+'/verification/browser.json',JSON.stringify({tested_at:new Date().toISOString(),url:page.url(),browser:'Chromium 154',source:'browser/Quadrotor_browser.mo',runs,syntax_error_markers:markers,page_errors:errors,scope:'Actual public editor UI: waited for Runtime Ready, pasted bundle, clicked lightning-bolt Create Scenario, set Model name BrowserFlight and Batch end time 8 s, saved and ran both drag settings. Produced result plots and tested syntax diagnostics. Python backends execute separately.'},null,2)+'\n');
await browser.close();
console.log(runs);
